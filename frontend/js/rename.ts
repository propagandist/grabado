/*
 * grabado: リネームの伝播で使う文字列置換（#213）。
 *
 * Row.setTitle と Table.setTitle の 2 か所から呼ばれる。1 行の重複を 2 クラスに置くかわりに
 * 1 本にしてあるのは js/identifier-hint.ts と同じ形で、理由も同じ ——
 * **規則をどちらか一方に書くと、もう一方が置いていかれる**。
 *
 * ★★ **置換の両側がユーザー入力**であることが、この関数の存在理由。
 *
 *   - **旧名は正規表現に渡していた。** `new RegExp(old, "g")` は `old` がテーブル名や列名
 *     そのものなので、`items)` のような打ち間違いで **SyntaxError**、`Products (old)` は
 *     valid だが `(old)` がキャプチャグループになって**自分自身に当たらず**、`user.name` は
 *     `.` が任意 1 文字に当たって**誤置換**する（2026-09-09 実測。3 通りの壊れ方が出る）。
 *   - **新名は置換文字列に渡していた。** String.prototype.replace は第 2 引数の `$&` /
 *     `` $` `` / `$'` / `$1` / `$$` を特別扱いするので、`$&x` にリネームすると
 *     **一致テキストが子行名に注入される**。関数を渡せばこの解釈は起きない。
 *
 * ★ **空の旧名は現行のまま**（`new RegExp("", "g")` と同じで、1 文字ごとに新名が挟まる）。
 *   split/join へ置き換えれば挙動が変わるが、**到達しないことに依存する証明を避ける**という
 *   #213 の判断に従い、規則を変えずにエスケープだけを足す。実際の値は
 *   tests/node/rename.test.ts がリテラルで固定している。
 */

/**
 * `text` の中の `from` を、**リテラルとして**すべて `to` に置き換える。
 *
 * 正規表現としても置換文字列としても解釈しない。一致が無ければ `text` と同一の文字列を
 * 返す（呼び手は `!=` で「変わったか」を見て再帰を止める）。
 */
export function renameOccurrences(text: string, from: string, to: string): string {
    /* 置換側は関数にする —— 文字列で渡すと $& などが展開される */
    return text.replace(new RegExp(escapeRegExp(from), "g"), () => to);
}

/*
 * 正規表現のメタ文字を落とす。RegExp.escape は ES2025 で、tsconfig の lib が ES2022 の
 * あいだは型検査が通らない —— lib を上げる日にこの 3 行ごと置き換えられる。
 */
function escapeRegExp(s: string): string {
    return s.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
}
